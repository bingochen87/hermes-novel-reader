#!/usr/bin/env node
/**
 * Inline src/core.js into src/plugin.js and emit dist/plugin.js.
 *
 * The disk-plugin loader only resolves three specifiers (`@hermes/plugin-sdk`,
 * `react`, `react/jsx-runtime`), so the pure helpers cannot be a second module
 * at runtime. They stay a separate file for testing, and ship concatenated.
 *
 *   node build.mjs           write dist/plugin.js
 *   node build.mjs --check   fail when dist/plugin.js is stale
 */

import { readFile, writeFile } from 'node:fs/promises'

const ROOT = new URL('./', import.meta.url)
const BLOCK = /\/\/ ---8<--- core:[\s\S]*?\/\/ ---8<--- end core ---8<---/

const plugin = await readFile(new URL('src/plugin.js', ROOT), 'utf8')
const core = await readFile(new URL('src/core.js', ROOT), 'utf8')

if (!BLOCK.test(plugin)) {
  console.error('build: src/plugin.js is missing the core inline block markers')
  process.exit(1)
}

const coreBody = core
  .replace(/^export (?=(?:async )?function|const|class|let)/gm, '')
  .trim()

const banner = [
  '// Generated by build.mjs from src/plugin.js + src/core.js — do not edit directly.',
  '// Install: cp dist/plugin.js ~/.hermes/desktop-plugins/novel-reader/plugin.js',
  ''
].join('\n')

const output = `${banner}${plugin.replace(BLOCK, `// --- core (src/core.js) ---\n${coreBody}\n// --- end core ---`)}`
const target = new URL('dist/plugin.js', ROOT)

if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '')

  if (existing !== output) {
    console.error('build: dist/plugin.js is stale — run `npm run build`')
    process.exit(1)
  }

  console.log('build: dist/plugin.js is up to date')
  process.exit(0)
}

await writeFile(target, output)
console.log(`build: wrote dist/plugin.js (${(output.length / 1024).toFixed(1)} KB)`)
